// Quotation Storage Utility - Database Version
// Handles saving and retrieving quotations from database via API

const QUOTATIONS_API_BASE = '/api/quotations';

// Generate unique quotation ID (fallback for client-side)
export const generateQuotationId = () => {
  const date = new Date();
  const dateStr = date.toISOString().split('T')[0].replace(/-/g, '');
  const timestamp = Date.now().toString().slice(-6);
  return `QTN-${dateStr}-${timestamp}`;
};

// Save quotation to database via API
export const saveQuotation = async (quotationData) => {
  try {
    // Ensure quotation has required fields
    const quotation = {
      id: quotationData.id || generateQuotationId(),
      status: quotationData.status || 'DRAFT',
      orderSettings: quotationData.orderSettings || {},
      lineItems: quotationData.lineItems || [],
      totals: quotationData.totals || {},
      termsAndConditions: quotationData.termsAndConditions || {},
      bulkCalculation: quotationData.bulkCalculation || {},
      // Add required database fields
      partyName: quotationData.orderSettings?.customerName || 'Unknown Customer',
      quotationDate: quotationData.createdAt || new Date().toISOString(),
      srNo: quotationData.srNo || null, // Will be auto-generated by API
      ...quotationData
    };

    const response = await fetch(QUOTATIONS_API_BASE, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(quotation)
    });

    const result = await response.json();
    
    if (result.success) {
      return {
        success: true,
        quotationId: result.data.id,
        quotation: result.data
      };
    } else {
      throw new Error(result.error || 'Failed to save quotation');
    }
  } catch (error) {
    console.error('Error saving quotation:', error);
    return {
      success: false,
      error: error.message || 'Failed to save quotation'
    };
  }
};

// Get all quotations from database via API
export const getQuotations = async (filters = {}) => {
  try {
    const queryParams = new URLSearchParams();
    
    // Add filters to query params
    Object.keys(filters).forEach(key => {
      if (filters[key]) {
        queryParams.append(key, filters[key]);
      }
    });

    const response = await fetch(`${QUOTATIONS_API_BASE}?${queryParams.toString()}`);
    const result = await response.json();
    
    if (result.success) {
      return result.data;
    } else {
      throw new Error(result.error || 'Failed to fetch quotations');
    }
  } catch (error) {
    console.error('Error retrieving quotations:', error);
    return [];
  }
};

// Get a specific quotation by ID
